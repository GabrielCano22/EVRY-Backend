function limpiar(texto: string) {
  return texto
    .replace(/\s+/g, ' ')
    .replace(/\(\s*\)/g, '')
    .replace(/\s+([,)])/g, '$1')
    .replace(/([,(])\s+/g, '$1 ')
    .replace(/\s+-\s*/g, ' - ')
    .trim();
}

function normalizarNombreCanonico(texto: string) {
  return texto
    .replace(/\blastrado\s+(sentadilla|zancada|prensa|extensi[oó]n)\b/gi, '$1 lastrada')
    .replace(/\blastrado\s+(curl)\b/gi, '$1 lastrado')
    .replace(/\bpress\s+banca\b/gi, 'press de banca')
    .replace(/\bdominadas\s+agarre\b/gi, 'dominadas con agarre');
}

/** Revisados sustituidos por una revisión posterior; solo se aceptan como estado previo exacto. */
const NOMBRES_REVISADOS_ANTERIORES = new Map<string, string>([
  ['hands bike', 'Bicicleta de manos'],
  ['walking on stepmill', 'Caminata en escalera mecánica'],
  ['ski ergometer', 'Esquí ergómetro'],
  ['cocoons', 'Capullos'],
  ['balance board', 'Ejercicio de equilibrio en tabla'],
  ['v-sit on floor', 'Sentada en V en el suelo'],
]);

export function nombreRevisado(nombre: string): string | undefined {
  return NOMBRES_REVISADOS.get(nombre.trim().replace(/\s+/g, ' ').toLowerCase());
}

export function nombreRevisadoAnterior(nombre: string): string | undefined {
  return NOMBRES_REVISADOS_ANTERIORES.get(nombre.trim().replace(/\s+/g, ' ').toLowerCase());
}

export function traducirNombreOriginal(nombre: string) {
  let resultado = nombre.replace(/\s*\((male|female)\)\s*/gi, ' ').replace(/\s+/g, ' ').trim();
  for (const [patron, reemplazo] of REEMPLAZOS) resultado = resultado.replace(patron, reemplazo);
  resultado = normalizarNombreCanonico(limpiar(resultado));
  return resultado ? `${resultado[0].toLocaleUpperCase('es-CO')}${resultado.slice(1)}` : 'Ejercicio';
}

export function traducirNombreEjercicio(nombre: string) {
  return nombreRevisado(nombre) ?? traducirNombreOriginal(nombre);
}
